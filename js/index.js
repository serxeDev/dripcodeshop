    const ALL_ITEMS = "all";

    /**
     * Resolve the current page size into a real number.
     * "ALL" means every item fits on one page, so the size is the total
     * number of items. (Using Infinity here would break the slice math
     * with 0 * Infinity = NaN.)
     * @param {number} totalItems  how many items match the current filters
     */
    function getPageSize(totalItems) {
      if (itemsPerPage === ALL_ITEMS) return Math.max(1, totalItems || 0);
      return itemsPerPage;
    }

    /** Restore the saved page size and reflect it in the dropdown. */
    function restorePageSize() {
      let saved = null;
      try {
        saved = localStorage.getItem("drippy-page-size");
      } catch (err) {
        /* storage unavailable — ignore */
      }

      if (saved === ALL_ITEMS) {
        itemsPerPage = ALL_ITEMS;
      } else if (saved !== null && !Number.isNaN(parseInt(saved, 10))) {
        itemsPerPage = parseInt(saved, 10);
      }

      const select = document.getElementById("itemsPerPageSelect");
      if (select) {
        // Only reflect values that exist in the dropdown
        const optionExists = Array.from(select.options).some((opt) => opt.value === String(itemsPerPage));
        select.value = optionExists ? String(itemsPerPage) : String(ITEMS_PER_PAGE_DEFAULT);
      }
    }

