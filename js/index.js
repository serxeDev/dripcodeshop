    /**
     * Code Detail Modal — big pixel preview, zoom, and full code info.
     */
    let codeModalItemId = null;

    function openCodeModal(itemId) {
      const item = graalCodesData.find((entry) => entry.id === itemId);
      if (!item) return;

      codeModalItemId = itemId;
      refreshCodeModal();

      // Show
      const modal = document.getElementById("codeModal");
      modal.classList.remove("hidden");
      modal.classList.add("flex");
      document.body.style.overflow = "hidden";
    }

    /**
     * (Re)fill the code detail modal for the currently open item.
     * Called on open and whenever the locale changes.
     */
    function refreshCodeModal() {
      const item = graalCodesData.find((entry) => entry.id === codeModalItemId);
      if (!item) return;

      // Title
      const title = document.getElementById("codeModalTitle");
      if (title) title.textContent = I18N.t("items." + item.id + ".name", item.name);

      // Badges (same styling language as the cards)
      const badgesWrap = document.getElementById("codeModalBadges");
      if (badgesWrap) {
        badgesWrap.innerHTML = item.badges
          .map(
            (badge, i) => `
            <span class="font-pixel text-[10px] uppercase tracking-wider px-2 py-0.5 rounded border ${
              i === 0
                ? "text-[#3B82F6] border-[#3B82F6]/40 bg-[#3B82F6]/10"
                : "text-[#8E8D88] border-[#2E3138] bg-[#141518]"
            }" data-i18n="common.${badge}">
              ${I18N.t("common." + badge, badge)}
            </span>`
          )
          .join("");
      }

      // Big sprite: use the real image when there is one, otherwise the SVG
      const spriteWrap = document.getElementById("codeModalSprite");
      if (spriteWrap) {
        spriteWrap.innerHTML = item.image
          ? `<img
               src="${item.image}"
               alt="${I18N.t("items." + item.id + ".name", item.name)}"
               class="sprite-image modal-sprite-image"
             />`
          : item.svg.replace(/class="w-24 h-24 pixel-art"/g, 'class="pixel-art"');
      }

      // Code
      const codeEl = document.getElementById("codeModalCode");
      if (codeEl) {
        codeEl.textContent = item.code;
        codeEl.title = item.code;
      }

      // Meta
      const viewsEl = document.getElementById("codeModalViews");
      if (viewsEl) viewsEl.textContent = formatNumber(item.views);

      // Save button: reflect whether this code is already bookmarked
      const saveBtn = document.getElementById("codeModalSaveBtn");
      if (saveBtn) {
        saveBtn.setAttribute("data-save-btn", item.id);
        refreshSaveButtons(item.id);
      }
    }

    function closeCodeModal() {
      const modal = document.getElementById("codeModal");
      modal.classList.add("hidden");
      modal.classList.remove("flex");
      document.body.style.overflow = "";
      codeModalItemId = null;
    }

    /**
     * Copy the code straight from the detail modal.
     */
    function copyFromModal() {
      if (codeModalItemId === null) return;
      const item = graalCodesData.find((entry) => entry.id === codeModalItemId);
      if (!item) return;

      const tempInput = document.createElement("textarea");
      tempInput.value = item.code;
      tempInput.style.position = "fixed";
      tempInput.style.opacity = "0";
      document.body.appendChild(tempInput);
      tempInput.select();
      try {
        document.execCommand("copy");
      } catch (err) {
        console.error("Copy failed", err);
      }
      document.body.removeChild(tempInput);

      // Keep the card view counter in sync too
      item.views += 1;
      const viewSpan = document.getElementById(`views-count-${item.id}`);
      if (viewSpan) viewSpan.textContent = formatNumber(item.views);
      const modalViews = document.getElementById("codeModalViews");
      if (modalViews) modalViews.textContent = formatNumber(item.views);

      // Button feedback
      const btn = document.getElementById("codeModalCopyBtn");
      if (btn) {
        btn.classList.remove("bg-[#3B82F6]", "hover:bg-[#2563EB]");
        btn.classList.add("bg-[#F59E0B]", "text-[#141518]");
        btn.innerHTML = `<span>${I18N.t("copied", "COPIED!")}</span>`;

        setTimeout(() => {
          btn.classList.remove("bg-[#F59E0B]", "text-[#141518]");
          btn.classList.add("bg-[#3B82F6]", "hover:bg-[#2563EB]");
          btn.innerHTML = `
            <svg class="w-3.5 h-3.5" fill="none" stroke="currentColor" stroke-width="2" viewBox="0 0 24 24">
              <path stroke-linecap="round" stroke-linejoin="round" d="M8 16H6a2 2 0 01-2-2V6a2 2 0 012-2h8a2 2 0 012 2v2m-6 12h8a2 2 0 002-2v-8a2 2 0 00-2-2h-8a2 2 0 00-2 2v8a2 2 0 002 2z" />
            </svg>
            <span>${I18N.t("copy", "COPY")}</span>
          `;
        }, 1600);
      }

      showToast(`Copied: ${item.code}`);
    }

